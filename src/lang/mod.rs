    pub fn found_mangas(&self, n: usize) -> String {
        self.fmt_found.replacen("{}", &n.to_string(), 1)
    }
    pub fn found_scanner(&self, n: usize) -> String {
        self.fmt_found_scanner.replacen("{}", &n.to_string(), 1)
    }
    pub fn found_scanner2(&self, n: usize) -> String {
        self.fmt_found_scanner2.replacen("{}", &n.to_string(), 1)
    }
    pub fn error_msg(&self, msg: &str) -> String {
        self.fmt_error.replacen("{}", msg, 1)
    }
    pub fn chapter_label(&self, n: usize) -> String {
        self.fmt_chapter.replacen("{}", &n.to_string(), 1)
    }
    pub fn page_label(&self, n: usize) -> String {
        self.fmt_page.replacen("{}", &n.to_string(), 1)
    }
    pub fn gl_chapter(&self, cur: usize, total: usize) -> String {
        self.fmt_gl
            .replacen("{}", &cur.to_string(), 1)
            .replacen("{}", &total.to_string(), 1)
    }

    pub fn is_ru(&self) -> bool {
        std::ptr::eq(self.nav_library, Self::ru().nav_library)
    }
    pub fn is_en(&self) -> bool {
        std::ptr::eq(self.nav_library, Self::en().nav_library)
    }

    pub fn from_code(code: &str) -> Lang {
        match code {
            "ru" => Self::ru(),
            _ => Self::en(),
        }
    }
